# -*- coding: utf-8 -*-
"""
load_flood_pg.py — 生成 SQL 把 P0b 结果写入 PostGIS:
  flood_scenarios (每重现期一行)
  flood_extent    (淹没范围矢量, Polygon 4326)
flood_depth 栅格表由 raster2pgsql 单独加载(见 load_flood.sh)。
"""
import os, json, math
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # pipeline/ 子目录 -> 仓库根

OUT = os.path.join(ROOT, "flood_out", "load_flood.sql")
SCEN = os.path.join(ROOT, "flood_out", "scenarios.json")
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))   # pipeline/ 子目录: 仓库根入 path(共享模块 pipeline_config/proj_fix/...)
from pipeline_config import RETURNS   # 重现期档位唯一权威定义

DDL_SCEN = """
DROP TABLE IF EXISTS flood_scenarios;
CREATE TABLE flood_scenarios (
  return_period_y int PRIMARY KEY,
  rain_mm double precision,
  runoff_depth_m double precision,
  water_level_m double precision,
  max_depth_m double precision,
  mean_depth_m double precision,
  flooded_area_km2 double precision,
  flooded_cells int,
  river_cells int
);
"""

DDL_EXT = """
DROP TABLE IF EXISTS flood_extent;
CREATE TABLE flood_extent (
  gid serial PRIMARY KEY,
  return_period_y int,
  geom geometry(Polygon, 4326)
);
CREATE INDEX flood_extent_geom_idx ON flood_extent USING gist(geom);
CREATE INDEX flood_extent_t_idx ON flood_extent(return_period_y);
"""


def sql_literal(value):
    """将 JSON 标量适配为离线 PostgreSQL 字面量；不建立数据库连接。

    字符串显式用 E'' 并转义反斜杠/单引号，不依赖会话 standard_conforming_strings。
    拒绝 SQL 无法表示的 NUL、非有限浮点及非标量，避免静默生成损坏 SQL。
    """
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError("SQL 数值必须有限")
        return repr(value)
    if isinstance(value, str):
        if "\x00" in value:
            raise ValueError("PostgreSQL 文本不允许 NUL")
        return "E'" + value.replace("\\", "\\\\").replace("'", "''") + "'"
    raise TypeError("仅支持 JSON 标量 SQL 字面量")


def main():
    with open(SCEN, encoding="utf-8") as f:
        scenes = json.load(f)
    lines = ["-- auto-generated by load_flood_pg.py", DDL_SCEN]
    columns = ("return_period_y", "rain_mm", "runoff_depth_m", "water_level_m",
               "max_depth_m", "mean_depth_m", "flooded_area_km2", "flooded_cells", "river_cells")
    for s in scenes:
        values = ", ".join(sql_literal(s[c]) for c in columns)
        lines.append("INSERT INTO flood_scenarios VALUES (%s);" % values)

    lines.append(DDL_EXT)
    n = 0
    for T in RETURNS:
        with open(os.path.join(ROOT, "flood_out", "flood_extent_%dy.geojson" % T),
                  encoding="utf-8") as src:
            gj = json.load(src)
        for f in gj["features"]:
            g = json.dumps(f["geometry"], separators=(",", ":"), allow_nan=False)
            lines.append(
                "INSERT INTO flood_extent (return_period_y, geom) VALUES (%s, ST_GeomFromGeoJSON(%s));"
                % (sql_literal(T), sql_literal(g)))
            n += 1
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote %s  (scenarios=%d, extent polygons=%d)" % (OUT, len(scenes), n))


if __name__ == "__main__":
    main()
